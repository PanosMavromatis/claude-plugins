# --- running them -----------------------------------------------------------------------------

def sh(args, cwd, env=None, stdin=None):
    return subprocess.run(args, cwd=cwd, capture_output=True, text=True, env=env, input=stdin)
def git(*a, cwd):
    r = sh(["git", *a], cwd)
    if r.returncode: sys.exit(f"git {' '.join(a)} failed in {cwd}: {r.stderr}")
    return r.stdout
def write(root, files):
    for rel, text in files.items():
        p = f"{root}/{rel}"; os.makedirs(os.path.dirname(p), exist_ok=True)
        open(p, "w").write(text)

def build():
    for d in (FX, RUN, OUT): shutil.rmtree(d, ignore_errors=True)
    for name, (files, after, gone) in FIXTURES.items():
        repo = f"{FX}/{name}"; os.makedirs(repo)
        git("init", "-q", "-b", "main", cwd=repo)
        for k, v in (("user.email", "suite@example.invalid"), ("user.name", "suite"), ("commit.gpgsign", "false")):
            git("config", k, v, cwd=repo)
        write(repo, files)
        git("add", "-A", cwd=repo); git("commit", "-q", "-m", "fixture", cwd=repo)
        write(repo, after)
        for rel in gone: os.remove(f"{repo}/{rel}")
    for prog, targets in (("bash", SHELLS), ("python3", PYTHONS)):
        for t in targets:
            d = bindir(prog, t); shutil.rmtree(d, ignore_errors=True); os.makedirs(d)
            os.symlink(t, f"{d}/{prog}")
    for p in (GITLINK, GITSYM, W + "/ad-gitreal", DOCLINK, DOTSYM, W + "/ad-code"):
        if os.path.islink(p): os.remove(p)
        else: shutil.rmtree(p, ignore_errors=True)
    os.symlink(FX + "/pair/.git", GITLINK)   # no .git in the path as written, only once resolved
    os.makedirs(W + "/ad-gitreal"); os.makedirs(GITSYM); os.symlink(W + "/ad-gitreal", GITSYM + "/.git")   # the reverse
    os.makedirs(W + "/ad-code"); write(W + "/ad-code", {"app.py": "x\n"}); os.symlink(W + "/ad-code/app.py", DOCLINK)
    os.makedirs(DOTSYM); os.symlink(FX + "/pair/docs", DOTSYM + "/.claude")
    d = bindir("mktemp", MKTEMP); shutil.rmtree(d, ignore_errors=True); os.makedirs(d)
    open(d + "/mktemp", "w").write(f'#!/bin/sh\nd="$({MKTEMP} "$@")" || exit $?\necho "$d" >> "{MKLOG}"\necho "$d"\n')
    os.chmod(d + "/mktemp", 0o755)

def snap(root):  # every file under root but .git/, by path
    out = {}
    if not os.path.isdir(root): return out
    for d, dirs, files in os.walk(root):
        if d == root and ".git" in dirs: dirs.remove(".git")
        for f in files:
            p = os.path.join(d, f); out[os.path.relpath(p, root)] = open(p, "rb").read()
    return out
def state(repo):  # what "untouched" means: every file, git's view of them, and HEAD
    return snap(repo), git("status", "--porcelain", "--untracked-files=all", cwd=repo), git("rev-parse", "HEAD", cwd=repo)
def env_for(prog, target):
    env = dict(os.environ)
    for k in ("DST_DIR", "CLAUDE_PROJECT_DIR", "WORKFLOW_CODING_GUARDED_AGENTS"): env.pop(k, None)
    env["PATH"] = bindir(prog, target) + ":" + env["PATH"]
    return env
def first(got, want):
    bad = next((f"{g!r} want {w!r}" for g, w in zip(got, want) if g != w), None)
    return bad or f"{len(got)} lines, want {len(want)}: {got[len(want):][:2] or want[len(got):][:2]}"

def run_build(exp, fx, shell):
    """Two runs on one fresh copy: the first must leave the pair and touch nothing else, the
    second must print the same and change nothing."""
    probs = []
    for d in (RUN, OUT): shutil.rmtree(d, ignore_errors=True)
    shutil.copytree(f"{FX}/{fx}", RUN, symlinks=True)
    env = env_for("bash", shell)
    if exp.get("dst"): env["DST_DIR"] = OUT
    cwd = RUN + ("/" + exp["cwd"] if "cwd" in exp else "")
    before = snap(RUN); outs, prev = [], None
    for n in (1, 2):
        r = sh([shell, BUILD], cwd, env); outs.append((r.returncode, r.stdout, r.stderr))
        after, out = snap(RUN), snap(OUT)
        if n == 2:
            if outs[1] != outs[0]: probs.append("a second build printed something else")
            if (after, out) != prev: probs.append("a second build changed files")
            break
        prev = (after, out)
        if r.returncode != exp["exit"]: probs.append(f"exit {r.returncode}, want {exp['exit']} (stderr: {r.stderr.strip()[:100]!r})")
        want_err = exp.get("err", "").format(root=RUN)
        if r.stderr != want_err: probs.append(f"stderr: {first(r.stderr.splitlines(), want_err.splitlines())}")
        built = {p: c.encode() for p, c in PAIR.items()} if exp.get("built") else {}
        base = OUT if exp.get("dst") else RUN
        want_out = "".join(f"wrote {base}/{p} ({PAIR[p].count(chr(10))} lines)\n" for p in ORDER if p in built)
        if r.stdout != want_out: probs.append(f"stdout: {first(r.stdout.splitlines(), want_out.splitlines())}")
        target = out if exp.get("dst") else after
        for p, b in built.items():
            if target.get(p) != b: probs.append(f"{p} is not the header and its guide")
        if exp.get("dst"):
            changed = {p for p in set(before) | set(after) if before.get(p) != after.get(p)}
            if changed: probs.append(f"the tree changed with DST_DIR set: {sorted(changed)}")
            extra = set(out) - set(built)
            if extra: probs.append(f"DST_DIR holds more than the pair: {sorted(extra)}")
        else:
            changed = {p for p in set(before) | set(after) if before.get(p) != after.get(p)}
            want = {p for p, b in built.items() if before.get(p) != b}
            if changed != want: probs.append(f"changed {sorted(changed)}, want {sorted(want)}")
    return probs, outs

def norm(s): return re.sub(r"(?m)^(---|\+\+\+) /.*$", r"\1 PATH", s)   # diff -u's headers name temporary files

def run_check(exp, fx, shell):
    probs = []; repo = f"{FX}/{fx}"
    if os.path.exists(MKLOG): os.remove(MKLOG)
    env = env_for("bash", shell); env["PATH"] = bindir("mktemp", MKTEMP) + ":" + env["PATH"]
    before = state(repo)
    r = sh([shell, CHECK], repo + ("/" + exp["cwd"] if "cwd" in exp else ""), env)
    if state(repo) != before: probs.append("the fixture changed")
    made = open(MKLOG).read().split() if os.path.exists(MKLOG) else []
    if not made: probs.append("no temporary directory was made, so its removal went untested")
    for d in made:
        if os.path.exists(d): probs.append("the temporary directory was left behind"); shutil.rmtree(d, ignore_errors=True)
    if r.returncode != exp["exit"]: probs.append(f"exit {r.returncode}, want {exp['exit']} (stderr: {r.stderr.strip()[:100]!r})")
    errl = r.stderr.splitlines()
    lint = [l for l in errl if l.startswith("warning: ") and not l.endswith("is a dispatcher-layout source this build ignores")]
    rest = [l for l in errl if l not in lint]
    want = ["warning: " + w for w in exp.get("warns", [])]
    if lint != want: probs.append(f"warnings: {first(lint, want)}")
    if "drift" in exp or "missing" in exp:
        if r.stdout: probs.append(f"stdout on a failed check: {r.stdout.strip()[:80]!r}")
        if rest.count(OUTOF) != 1: probs.append(f"the out-of-sync line {rest.count(OUTOF)} times")
        elif rest[0] != OUTOF: probs.append(f"first line {rest[0]!r}")
        if not rest or rest[-1] != FIX: probs.append(f"last line {(rest or [''])[-1]!r}")
        drift = [m.group(1) for m in (re.match(r"^--- drift in (.*) \(expected vs\. actual\) ---$", l) for l in rest) if m]
        if drift != exp.get("drift", []): probs.append(f"drift in {drift}, want {exp.get('drift', [])}")
        miss = [l for l in rest if l.startswith("missing: ")]
        want_m = [f"missing: {p} (run /agents-docs-build to generate)" for p in exp.get("missing", [])]
        if miss != want_m: probs.append(f"missing: {first(miss, want_m)}")
        for l in exp.get("diff", []):
            if l not in rest: probs.append(f"the diff lacks {l!r}")
    else:
        want_rest = exp.get("err", "").format(root=repo).splitlines()
        if rest != want_rest: probs.append(f"stderr: {first(rest, want_rest)}")
        want_out = exp["last"] + "\n" if "last" in exp else ""
        if r.stdout != want_out: probs.append(f"stdout {r.stdout!r}, want {want_out!r}")
    return probs, [(r.returncode, r.stdout, norm(r.stderr))]

def run_hook(exp, fx, py):
    probs = []; repo = f"{FX}/{fx}"
    env = env_for("python3", py)
    if exp.get("unset"): cwd = repo
    else: env["CLAUDE_PROJECT_DIR"] = repo; cwd = W
    if "seam" in exp: env["WORKFLOW_CODING_GUARDED_AGENTS"] = exp["seam"]
    if "raw" in exp: stdin = exp["raw"]
    else:
        ti = {}
        if exp["path"]: ti["file_path"] = exp["path"] if exp["path"].startswith("/") else f"{repo}/{exp['path']}"
        ti.update({"Write": {"content": "x\n"}, "Edit": {"old_string": "a", "new_string": "b"},
                   "MultiEdit": {"edits": [{"old_string": "a", "new_string": "b"}]}}.get(exp["tool"], {}))
        d = {"session_id": "suite", "hook_event_name": "PreToolUse", "cwd": repo, "tool_name": exp["tool"], "tool_input": ti}
        if exp.get("agent"): d.update(agent_type=exp["agent"], agent_id="a1")
        stdin = json.dumps(d)
    before = state(repo)
    r = sh([HOOK], cwd, env, stdin)   # as hooks.json runs it: the file itself, by its shebang
    if state(repo) != before: probs.append("the fixture changed")
    if r.returncode != exp["exit"]: probs.append(f"exit {r.returncode}, want {exp['exit']} (stderr: {r.stderr.strip()[:100]!r})")
    if r.stdout: probs.append(f"stdout {r.stdout[:80]!r}")
    if "prefix" in exp:
        if not r.stderr.startswith(exp["prefix"]): probs.append(f"stderr {r.stderr[:80]!r}")
    elif r.stderr != exp.get("err", ""): probs.append(f"stderr: {first(r.stderr.splitlines(), exp.get('err', '').splitlines())}")
    return probs, [(r.returncode, r.stdout, r.stderr)]

def static_checks():
    probs = []
    for p in (BUILD, CHECK):
        name = os.path.basename(p)
        code = "\n".join(l for l in open(p).read().splitlines() if not l.lstrip().startswith("#"))
        if "<<" in code: probs.append(f"{name}: a heredoc or here-string")
        for bad in ("globstar", "mapfile", "readarray", "declare -A", ",,}", "^^}"):
            if bad in code: probs.append(f"{name}: Bash 4 feature {bad}")
        if re.search(r"grep[^|\n]*\\\|", code): probs.append(f"{name}: grep with \\| alternation")
    return probs

def mutants():
    d = HERE + "/mutants"; tmp = W + "/ad-mut"; bad = 0
    shutil.rmtree(tmp, ignore_errors=True); os.makedirs(tmp)
    for fn in sorted(f for f in os.listdir(d) if f.endswith(".patch")):
        name = fn[:-6]; root = f"{tmp}/{name}"
        for f in UNDER_TEST:
            os.makedirs(os.path.dirname(f"{root}/{f}"), exist_ok=True); shutil.copy2(f"{PLUGIN}/{f}", f"{root}/{f}")
        ap = sh(["patch", "-s", "-F0", "-p1", "-d", root, "-i", f"{d}/{fn}"], tmp)
        if ap.returncode:
            bad += 1; print(f"STALE  {name}: the patch no longer applies ({(ap.stdout + ap.stderr).strip()[:120]})"); continue
        for f in UNDER_TEST: os.chmod(f"{root}/{f}", os.stat(f"{PLUGIN}/{f}").st_mode)
        r = sh([sys.executable, "-I", os.path.abspath(__file__), "--once", "--first", "--plugin", root], HERE)
        killed = r.returncode != 0
        why = next((l for l in r.stdout.splitlines() if l.startswith("FAIL") or (l.startswith("static:") and l != "static: ok")), "")
        if name in EQUIVALENT:
            ok = not killed; print(f"{'EQUIV ' if ok else 'CHANGED'} {name}")
        else:
            ok = killed; print(f"{'KILLED' if ok else 'SURVIVED'} {name}" + (f"  ({why[:100]})" if ok else ""))
        bad += not ok
    shutil.rmtree(tmp); print(f"\n{bad} failing"); sys.exit(1 if bad else 0)

def main():
    if "--mutants" in sys.argv: mutants()
    want = [a for a in sys.argv[1:] if re.match(r"^[bch]\d", a)]
    build()
    st = static_checks(); print("static: " + ("ok" if not st else "; ".join(st)))
    fails = len(st)
    runner = {"build": (run_build, SHELLS), "check": (run_check, SHELLS), "hook": (run_hook, PYTHONS)}
    for cid, kind, fx, exp in C:
        if want and cid not in want: continue
        fn, with_ = runner[kind]; outs, probs = set(), []
        for x in with_:
            for _ in range(1 if "--once" in sys.argv else 2):
                p, o = fn(exp, fx, x); outs.update(o)
                probs += [q for q in p if q not in probs]
        if len(outs) > (2 if kind == "build" else 1): probs.append("output differs between runs or shells")
        print(f"{'PASS' if not probs else 'FAIL'} {cid:<4} " + "; ".join(probs))
        if "-v" in sys.argv: print("".join(o[1] + o[2] for o in sorted(outs)))
        fails += bool(probs)
        if probs and "--first" in sys.argv: break   # a mutant needs one failure, not all of them
    print(f"\n{fails} failing"); sys.exit(1 if fails else 0)

main()
