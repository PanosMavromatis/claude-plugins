"""agents-docs suite: runs build-agents-md.sh, check-agents-md.sh and protect-agent-docs.py on
fixture repositories built here, most in the §4.3 layout, and grades what each prints and
writes. Writes only under $LOCATE_PLAN_WORK, which must lie outside the repository (the rule
dev/locate-plan/ uses: each fixture is a git repository).

  LOCATE_PLAN_WORK=<dir> python3 -I suite.py [-v] [--once] [--plugin PATH] [ids...]
  LOCATE_PLAN_WORK=<dir> python3 -I suite.py --mutants

The scripts run twice under each Bash found, and the hook twice under each python3 found,
each put first on PATH, so the check's own call to the build and the hook's shebang find it
too; every run must print the same thing. A build runs on a fresh copy of its fixture and
must change exactly the AGENTS.override.md files whose bytes differ from the header and their
guide, and a second run must change nothing. A check and a hook must leave their fixture
untouched, and a check must remove its temporary directory. --mutants applies each patch in
mutants/ to a copy of the two scripts and the hook, and runs the suite on it once, up to its
first failure (--first): each must fail it, and a patch that no longer applies is reported
stale. A patch names its file relative to the plugin's root (scripts/..., hooks/...)."""
