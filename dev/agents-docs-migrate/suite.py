# --- running and grading -------------------------------------------------------------------

def state(root):
    out = {}
    for d, dirs, files in os.walk(root):
        dirs[:] = [x for x in dirs if x != ".git"]
        for f in files:
            p = os.path.join(d, f); out[os.path.relpath(p, root)] = hashlib.sha1(open(p, "rb").read()).hexdigest()
    return out

def first(got, want):
    for i, (g, w) in enumerate(zip(got, want)):
        if g != w: return f"line {i + 1}: got {g!r}, want {w!r}"
    return f"{len(got)} lines, want {len(want)}"

def run(cid, fx, sub, code, want, py):
    root = f"{FX}/{fx}"; cwd = f"{root}/{sub}" if sub else root
    if cid == "d22": want = not_root(f"in {os.path.realpath(cwd)}, not at the root {os.path.realpath(root)}")
    if cid == "c20":
        missing = f"{FX}/replies/none.md"
        want = "".join(f"{k}: {v}\n" for k, v in (
            ("result", "error"), ("input", missing), ("rows", "—"), ("writes", "—"), ("unread", "—"), ("flags", "—"),
            ("drops", "—"), ("repointed", "—"), ("problem", f"cannot read {missing}: No such file or directory"),
            ("fix", "write docs-classifier's report to that file, then run this again"), ("message", "The table was not read.")))
    args = ([] if cid == "d24" else ["check", f"{FX}/replies/none.md"] if cid == "c20" else
            ["check", reply_path(cid)] if cid in REPLIES else ["detect"])
    before = state(root)
    r = subprocess.run([py, "-I", SCRIPT, *args], cwd=cwd, capture_output=True, text=True)
    probs = []
    if state(root) != before: probs.append("the fixture changed")
    if r.returncode != code: probs.append(f"exit {r.returncode}, want {code} (stderr: {r.stderr.strip()[:120]!r})")
    if cid == "d24":
        if r.stdout or not r.stderr.startswith("usage: "): probs.append(f"stdout {r.stdout[:60]!r}, stderr {r.stderr[:60]!r}")
    else:
        if r.stderr: probs.append(f"stderr {r.stderr.strip()[:120]!r}")
        if r.stdout != want: probs.append(first(r.stdout.splitlines(), want.splitlines()))
    return probs, (r.returncode, r.stdout, r.stderr)

def run_av(cid, fx, rid, steps, code, want, files, py):
    root = f"{FX}-run/{cid}"
    shutil.rmtree(root, ignore_errors=True); shutil.copytree(f"{FX}/{fx}", root, symlinks=True)
    expect = state(root)
    expect.update({p: hashlib.sha1(t.encode()).hexdigest() for p, (_, t) in files.items()})
    r = None
    for step in steps:
        if callable(step):
            step(root); continue
        r = subprocess.run([py, "-I", SCRIPT, step, reply_path(rid)], cwd=root, capture_output=True, text=True)
    assert r is not None, f"{cid} runs no mode"
    probs = []
    if r.returncode != code: probs.append(f"exit {r.returncode}, want {code} (stderr: {r.stderr.strip()[:120]!r})")
    if r.stderr: probs.append(f"stderr {r.stderr.strip()[:120]!r}")
    if r.stdout != want: probs.append(first(r.stdout.splitlines(), want.splitlines()))
    got = state(root)
    off = sorted(p for p in set(got) | set(expect) if got.get(p) != expect.get(p))
    if off: probs.append(f"files not as expected: {', '.join(off[:4])}")
    return probs, (r.returncode, r.stdout, r.stderr)

def mutants():
    d = HERE + "/mutants"; tmp = W + "/adm-mut"; bad = 0
    shutil.rmtree(tmp, ignore_errors=True); os.makedirs(tmp)
    for fn in sorted(f for f in os.listdir(d) if f.endswith(".patch")):
        name = fn[:-6]; root = f"{tmp}/{name}"
        for f in UNDER_TEST:
            os.makedirs(os.path.dirname(f"{root}/{f}"), exist_ok=True); shutil.copy2(f"{PLUGIN}/{f}", f"{root}/{f}")
        ap = subprocess.run(["patch", "-s", "-F0", "-p1", "-d", root, "-i", f"{d}/{fn}"], capture_output=True, text=True)
        if ap.returncode:
            bad += 1; print(f"STALE  {name}: the patch no longer applies ({(ap.stdout + ap.stderr).strip()[:120]})"); continue
        r = subprocess.run([sys.executable, "-I", os.path.abspath(__file__), "--once", "--first", "--plugin", root],
                           cwd=HERE, capture_output=True, text=True)
        killed = r.returncode != 0
        why = next((l for l in r.stdout.splitlines() if l.startswith("FAIL")), "")
        if name in EQUIVALENT:
            ok = not killed; print(f"{'EQUIV ' if ok else 'CHANGED'} {name}")
        else:
            ok = killed; print(f"{'KILLED' if ok else 'SURVIVED'} {name}" + (f"  ({why[:100]})" if ok else ""))
        bad += not ok
    shutil.rmtree(tmp); print(f"\n{bad} failing"); sys.exit(1 if bad else 0)

def main():
    if "--mutants" in sys.argv: mutants()
    want = [a for a in sys.argv[1:] if re.match(r"^[dcav]\d", a)]
    build()
